import archiver from 'archiver';

export function createProjectZip(project) {
  return new Promise((resolve, reject) => {
    const archive = archiver('zip', {
      zlib: { level: 9 } // Maximum compression
    });

    const buffers = [];
    archive.on('data', (data) => buffers.push(data));
    archive.on('end', () => resolve(Buffer.concat(buffers)));
    archive.on('error', (err) => reject(err));

    // Append each file to the archive maintaining folder structure
    if (project.files && Array.isArray(project.files)) {
      for (const file of project.files) {
        archive.append(file.content || '', { name: file.path || file.name });
      }
    }

    // Also include ARCHITECTURE.md, SCHEMA.md, API.md, and PROJECT_PLAN.md
    if (project.requirementsAnalysis) {
      archive.append(generateRequirementsMd(project), { name: 'docs/REQUIREMENTS.md' });
    }
    if (project.projectPlan) {
      archive.append(generatePlanMd(project), { name: 'docs/PROJECT_PLAN.md' });
    }
    if (project.architecture) {
      archive.append(generateArchitectureMd(project), { name: 'docs/ARCHITECTURE.md' });
    }
    if (project.schemaDesign) {
      archive.append(generateSchemaMd(project), { name: 'docs/DATABASE_SCHEMA.md' });
    }
    if (project.apiEndpoints) {
      archive.append(generateApiMd(project), { name: 'docs/API_DOCUMENTATION.md' });
    }

    archive.finalize();
  });
}

function generateRequirementsMd(p) {
  const req = p.requirementsAnalysis;
  return `# Requirements Analysis: ${p.title}
Generated by CodeMind AI

## Overview
${req?.overview || p.prompt}

## Target User Roles
${req?.targetUsers?.map(u => `### ${u.role}\n${u.capabilities?.map(c => `- ${c}`).join('\n')}`).join('\n\n') || 'Standard User & Admin'}

## Functional Modules
${req?.modules?.map(m => `### ${m.name}\n${m.features?.map(f => `- ${f}`).join('\n')}`).join('\n\n') || ''}

## Non-Functional Requirements
${req?.nonFunctionalRequirements?.map(n => `- ${n}`).join('\n') || ''}
`;
}

function generatePlanMd(p) {
  const plan = p.projectPlan;
  return `# Project Plan: ${p.title}
Generated by CodeMind AI

## Milestones & Roadmap
${plan?.milestones?.map(m => `### ${m.phase} (${m.duration})\n${m.tasks?.map(t => `- [x] ${t}`).join('\n')}`).join('\n\n') || ''}

## Deliverables
${plan?.deliverables?.map(d => `- ${d}`).join('\n') || ''}
`;
}

function generateArchitectureMd(p) {
  const arch = p.architecture;
  return `# System Architecture: ${p.title}
Generated by CodeMind AI

## Architectural Pattern
**${arch?.pattern || 'Decoupled Client-Server'}**

${arch?.description || ''}

## System Components
${arch?.components?.map(c => `- **${c.name}** (${c.technology}): ${c.role}`).join('\n') || ''}

## Data Flow Diagram
\`\`\`
${arch?.diagram || ''}
\`\`\`
`;
}

function generateSchemaMd(p) {
  const schema = p.schemaDesign;
  return `# Database Schema & Entities: ${p.title}
Generated by CodeMind AI

${schema?.collections?.map(c => `### Collection / Table: ${c.name}
| Field | Type | Attributes | Description |
|---|---|---|---|
${c.fields?.map(f => `| \`${f.name}\` | \`${f.type}\` | ${f.required ? '**Required**' : 'Optional'} | ${f.description || ''} |`).join('\n')}
`).join('\n\n') || ''}

## Entity Relationships
${schema?.relationships?.map(r => `- ${r}`).join('\n') || ''}
`;
}

function generateApiMd(p) {
  const apis = p.apiEndpoints;
  return `# API Endpoints Reference: ${p.title}
Generated by CodeMind AI

| Method | Endpoint | Authorization | Description |
|---|---|---|---|
${apis?.map(a => `| **${a.method}** | \`${a.path}\` | ${a.auth} | ${a.description} |`).join('\n') || ''}

## Endpoint Details
${apis?.map(a => `### ${a.method} ${a.path}
- **Description**: ${a.description}
- **Auth**: ${a.auth}
- **Request Body**: \`${a.request}\`
- **Response**: \`${a.response}\`
`).join('\n') || ''}
`;
}
